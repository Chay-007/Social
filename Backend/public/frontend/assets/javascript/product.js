// List View
function listView() {
    $("#addremove").removeClass("grid");
    $("#addremove").addClass("list");

    $(".fafa-list").css("color", "black");
    $(".fafa-grid").css("color", "#909294");
}

// Grid View
function gridView() {
    $("#addremove").removeClass("list");
    $("#addremove").addClass("grid");

    $(".fafa-grid").css("color", "black");
    $(".fafa-list").css("color", "#909294");
}


